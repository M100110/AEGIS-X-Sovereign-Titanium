import "strings"

// LookupMACVendor resolves IEEE OUI 24-bit prefixes (420+ major enterprise, consumer, mobile, TV, gaming & IoT prefixes)
// to exact Manufacturer + Device Family hints.
// Also detects IEEE 802 locally-administered MAC addresses (iOS 14+/Android 10+ Private Wi-Fi Address randomization).
func LookupMACVendor(mac string) (vendor string, familyHint string, isRandomized bool) {
	clean := strings.ToUpper(strings.ReplaceAll(strings.ReplaceAll(mac, ":", ""), "-", ""))
	if len(clean) < 6 {
		return "Unknown Vendor", "", false
	}
	prefix := clean[:6]
	if v, ok := ouiVendorTable[prefix]; ok {
		return v.vendor, v.hint, false
	}

	// Check IEEE Locally Administered Bit (2nd hex digit == 2, 6, A, E) -> iPhone / Android Private Wi-Fi MAC
	secondNib := clean[1]
	if secondNib == '2' || secondNib == '6' || secondNib == 'A' || secondNib == 'E' {
		return "Private Wi-Fi MAC (Apple iOS / Android Mobile)", "smartphone", true
	}
	return "Standard IEEE Network Device", "", false
}

